// FNV-1a 32-bit hash → hex string
function fnv32a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = (h * 0x01000193) >>> 0;
  }
  return ('00000000' + h.toString(16)).slice(-8).toUpperCase();
}

// MurmurHash3-inspired 32-bit string hash (fmix-style avalanche).
// Fixed: the original used floating-point multiplies that exceeded 2^53
// (silent precision loss) and `h = h & h`, a no-op intended to truncate.
// All arithmetic now stays in uint32 via Math.imul / |0.
function murmurhash3(str) {
  let h = 0xdeadbeef | 0;
  for (let i = 0; i < str.length; i++) {
    let c = str.charCodeAt(i);
    c = Math.imul(c ^ (c >>> 16), 0x45d9f3b);
    c = Math.imul(c ^ (c >>> 16), 0x45d9f3b);
    c = c ^ (c >>> 16);
    h ^= c;
    h = (Math.imul(h, 33) + c) | 0;   // 33h + c, kept in int32
  }
  return ('00000000' + (h >>> 0).toString(16)).slice(-8).toUpperCase();
}

// Combine multiple hash inputs into one master hash
function masterHash(parts) {
  return fnv32a(parts.join('|')) + '-' + murmurhash3(parts.join('~'));
}

// Render rows into a section body
function renderRows(bodyId, rows, countId) {
  const body = document.getElementById(bodyId);
  body.innerHTML = '';
  rows.forEach(([key, val, cls]) => {
    const row = document.createElement('div');
    row.className = 'row';
    const k = document.createElement('span');
    k.className = 'row-key';
    k.textContent = key;
    const v = document.createElement('span');
    v.className = 'row-val' + (cls ? ' ' + cls : '');
    v.innerHTML = val;
    row.appendChild(k);
    row.appendChild(v);
    body.appendChild(row);
  });
  if (countId) document.getElementById(countId).textContent = rows.length;
}

function appendRow(bodyId, key, val, cls) {
  const body = document.getElementById(bodyId);
  const row = document.createElement('div');
  row.className = 'row';
  const k = document.createElement('span'); k.className = 'row-key'; k.textContent = key;
  const v = document.createElement('span'); v.className = 'row-val' + (cls ? ' ' + cls : ''); v.innerHTML = val;
  row.appendChild(k); row.appendChild(v);
  body.appendChild(row);
  const cnt = document.getElementById(bodyId.replace('body-','cnt-'));
  if (cnt) cnt.textContent = body.querySelectorAll('.row').length;
}

function tag(text, cls) {
  return `<span class="tag ${cls}">${text}</span>`;
}
function yesno(b) { return b ? tag('YES','yes') : tag('NO','no'); }

// Escape HTML special chars — use for ANY value not generated by this script
// (HTTP headers, $_SERVER vars, UA strings, device labels, voice names…)
// before it is injected via innerHTML.
function esc(s) {
  return String(s).replace(/[&<>"']/g, ch => (
    {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]
  ));
}

// Probe whether a Web Storage area is actually usable (it can exist yet throw
// SecurityError on access when cookies/storage are blocked).
function storageUsable(type) {
  try {
    const s = window[type];
    const k = '__bp_probe__';
    s.setItem(k, '1');
    s.removeItem(k);
    return true;
  } catch (e) { return false; }
}

